import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8').replaceAll('\r\n','\n');
const json=p=>JSON.parse(read(p));
const version=json('package.json').version;
assert.match(version,/^\d+\.\d+\.\d+$/,'Formal releases use a stable numeric version');
const lock=json('package-lock.json');
for(const [name,value] of [['npm lock',lock.version],['npm root',lock.packages[''].version],['Chromium manifest',json('extension/manifest.json').version],['Firefox manifest',json('extension/manifest.firefox.json').version]])assert.equal(value,version,name);
assert.ok(read('native-host/Cargo.toml').includes(`version = "${version}"`));
assert.ok(read('native-host/Cargo.lock').includes(`name = "streamfirefly-native"\nversion = "${version}"`));
assert.ok(read('installer/StreamFirefly.iss').includes(`#define AppVersion "${version}"`));
assert.ok(read('INSTALL.md').includes(`# StreamFirefly ${version} 安装指南`));
assert.ok(read(`docs/releases/${version}.md`).includes(`# StreamFirefly ${version}`));
assert.ok(read('LICENSE').includes('Permission is hereby granted'));
assert.ok(read('native-host/THIRD_PARTY_NOTICES.md').includes('## serde '));
assert.ok(read('extension/THIRD_PARTY_NOTICES.md').includes('## mpd-parser '));
assert.equal(json('extension/manifest.firefox.json').browser_specific_settings.gecko.id,'streamfirefly@example.invalid');
assert.ok(read('tools/package-release.ps1').includes('[Parameter(Mandatory=$true)][string]$SignedFirefoxXpi'));
assert.ok(!read('tools/package-release.ps1').includes('AllowDirtySource'));
assert.ok(!read('tools/package-release.ps1').includes('-test.xpi'));
console.log(`Release ${version} source versions, licenses and signed-package prerequisites agree`);
